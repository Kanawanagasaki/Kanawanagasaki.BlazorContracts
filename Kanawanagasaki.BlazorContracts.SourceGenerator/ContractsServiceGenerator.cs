namespace Kanawanagasaki.BlazorContracts.SourceGenerator;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Collections.Immutable;

[Generator]
public class ContractsServiceGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var config = context.AnalyzerConfigOptionsProvider.Select((options, _) =>
        {
            options.GlobalOptions.TryGetValue("build_property.BlazorContracts", out var value);
            return value;
        });

        var handlersDeclarations = context.SyntaxProvider.CreateSyntaxProvider
        (
            static (node, _) => node is ClassDeclarationSyntax classDecl && classDecl.BaseList is not null,
            static (ctx, _) => ctx.SemanticModel.GetDeclaredSymbol((ClassDeclarationSyntax)ctx.Node)
        );

        var compilations = context.CompilationProvider
            .Combine(handlersDeclarations.Collect())
            .Select((tuple, _) =>
            {
                var (compilation, handlersSymbolds) = tuple;
                var ret = new List<HandlerMetadata>();

                foreach (var handler in handlersSymbolds)
                {
                    if (handler is null)
                        continue;
                    if (HandlerMetadata.TryCreate(handler, out var metadata) && metadata is not null)
                        ret.Add(metadata);
                }

                return ret.ToImmutableArray();
            });

        context.RegisterSourceOutput(config.Combine(compilations), Execute);
    }

    private void Execute(SourceProductionContext context, (string?, ImmutableArray<HandlerMetadata>) tuple)
    {
        var (config, list) = tuple;
        var optIns = config?.ToLowerInvariant().Split(',') ?? [];
        if (!optIns.Contains("serverservice"))
            return;

        var injectedServices = new Dictionary<string, string>();
        var withResponseContracts = new List<HandlerMetadata>();
        var noResponseContracts = new List<HandlerMetadata>();

        foreach (var meta in list)
        {
            foreach (var (injectedServiceType, _) in meta.HandlerInjectedServicesTypes)
            {
                if (!injectedServices.ContainsKey(injectedServiceType))
                    injectedServices[injectedServiceType] = $"_injected_service_" + (injectedServices.Count + 1);
            }

            if (meta.Contract.IsReturning)
                withResponseContracts.Add(meta);
            else
                noResponseContracts.Add(meta);
        }

        using var sw = new StringWriter();
        using var iw = new IndentedTextWriter(sw);
        iw.WriteLine("// <auto-generated/>");
        iw.WriteLine("namespace Kanawanagasaki.BlazorContracts;");

        iw.WriteLine();

        iw.WriteLine("""
            public static class ContractsServiceExtension
            {
                public static Microsoft.Extensions.DependencyInjection.IServiceCollection AddContracts(this Microsoft.Extensions.DependencyInjection.IServiceCollection services)
                {
                    services.AddScoped<Kanawanagasaki.BlazorContracts.IContractsService, ContractsService>();
                    return services;
                }
            }
            """);

        iw.WriteLine();

        iw.WriteLine("public class ContractsService : Kanawanagasaki.BlazorContracts.IContractsService");
        iw.WriteLineAndIncrease("{");

        iw.WriteLine("private readonly Microsoft.Extensions.Logging.ILogger<ContractsService> _logger;");
        foreach (var kv in injectedServices)
            iw.WriteLine($"private readonly {kv.Key} {kv.Value};");

        iw.WriteLine();

        iw.WriteLineAndIncrease("public ContractsService(");
        iw.WriteLine(string.Join(",\n", injectedServices.Select(kv => $"{kv.Key} {kv.Value}").Concat(["Microsoft.Extensions.Logging.ILogger<ContractsService> logger"])));
        iw.DecreaseAndWriteLine(")");
        iw.WriteLineAndIncrease("{");
        iw.WriteLine("this._logger = logger;");
        foreach (var kv in injectedServices)
            iw.WriteLine($"this.{kv.Value} = {kv.Value};");
        iw.DecreaseAndWriteLine("}");

        foreach (var metadata in list)
        {
            var returnTypeGenericPart = string.Empty;
            if (metadata.Contract.IsReturning)
                returnTypeGenericPart = $"<{metadata.Contract.ReturnFullyQualifiedName}>";

            iw.WriteLine();

            if (metadata.Contract.IsDisposableReturnType)
                iw.WriteLine($"public async Task<{Constants.DisposableContractResultFullName}<{metadata.Contract.ReturnFullyQualifiedName}>> ProcessAsync({metadata.Contract.FullyQualifiedName} contract, System.Threading.CancellationToken ct = default)");
            else if (metadata.Contract.IsReturning)
                iw.WriteLine($"public async Task<{Constants.ContractResultFullName}<{metadata.Contract.ReturnFullyQualifiedName}>> ProcessAsync({metadata.Contract.FullyQualifiedName} contract, System.Threading.CancellationToken ct = default)");
            else
                iw.WriteLine($"public async Task<{Constants.ContractResultFullName}> ProcessAsync({metadata.Contract.FullyQualifiedName} contract, System.Threading.CancellationToken ct = default)");
            iw.WriteLineAndIncrease("{");

            iw.WriteLine("try");
            iw.WriteLineAndIncrease("{");

            var constructorNames = metadata.HandlerConstructorInjectedServicesTypes
                .Select(x => injectedServices.TryGetValue(x.TypeName, out var fieldName) ? fieldName : null)
                .Where(x => x is not null);

            iw.Write($"var handler = new {metadata.HandlerFullyQualifiedName}({string.Join(",", constructorNames)})");
            if (0 < metadata.HandlerPropertiesInjectedServicesTypes.Count)
            {
                iw.WriteLine();
                iw.WriteLineAndIncrease("{");
                var isFirst = true;
                foreach (var injectProp in metadata.HandlerPropertiesInjectedServicesTypes)
                {
                    if (!injectedServices.TryGetValue(injectProp.TypeName, out var fieldName))
                        continue;

                    if (isFirst)
                        isFirst = false;
                    else
                        iw.WriteLine(",");

                    iw.Write($"{injectProp.Name} = {fieldName}");
                }
                iw.WriteLineAndDecrease("");
                iw.Write("}");
            }
            iw.WriteLine(";");
            iw.WriteLine("var result = await handler.HandleAsync(contract, ct);");
            if (metadata.Contract.IsDisposableReturnType)
                iw.WriteLine($"return result.AsDisposable();");
            else
                iw.WriteLine($"return result;");

            iw.DecreaseAndWriteLine("}");
            iw.WriteLine("catch (System.OperationCanceledException)");
            iw.WriteLineAndIncrease("{");
            if (metadata.Contract.IsDisposableReturnType)
                iw.WriteLine($"return new Kanawanagasaki.BlazorContracts.DisposableContractResult{returnTypeGenericPart}(499, \"Client Closed Request\");");
            else
                iw.WriteLine($"return new Kanawanagasaki.BlazorContracts.ContractResult{returnTypeGenericPart}(499, \"Client Closed Request\");");
            iw.DecreaseAndWriteLine("}");
            iw.WriteLine("catch (System.Exception e)");
            iw.WriteLineAndIncrease("{");
            iw.WriteLine("_logger.LogError(e, \"Failed to process a contract\");");
            if (metadata.Contract.IsDisposableReturnType)
                iw.WriteLine($"return new Kanawanagasaki.BlazorContracts.DisposableContractResult{returnTypeGenericPart}(500, \"Internal Server Error\");");
            else
                iw.WriteLine($"return new Kanawanagasaki.BlazorContracts.ContractResult{returnTypeGenericPart}(500, \"Internal Server Error\");");
            iw.DecreaseAndWriteLine("}");

            iw.DecreaseAndWriteLine("}");
        }

        iw.DecreaseAndWriteLine("}");

        context.AddSource("ContractsService.g.cs", sw.ToString());
    }
}
